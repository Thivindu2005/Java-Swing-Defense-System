//Add the operation permission method
public void updateOperationButtons(int position) {

    controllerPosition = position;

    if (chkPosition.isSelected()) {

        // Position 20 or above
        btnShoot.setEnabled(position >= 20);

        // Position 60 or above
        btnMissile.setEnabled(position >= 60);

        // Above position 80
        btnRadar.setEnabled(position > 80);

        btnRotate.setEnabled(position > 80);

    } else {

        btnShoot.setEnabled(false);

        btnMissile.setEnabled(false);

        btnRadar.setEnabled(false);

        btnRotate.setEnabled(false);
    }
}

public void receiveMessage(String message) {

    txtMessages.append(
        "MainController: " + message + "\n"
    );
}

public void updateAreaStatus(boolean cleared) {

    if (cleared) {
        lblAreaStatus.setText("Area Cleared");
    } else {
        lblAreaStatus.setText("Area Not Cleared");
    }
}

